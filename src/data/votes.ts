function nameOf(key: string) {
  return key.split('/')[1]
}

/** 以「縣市/姓名」為鍵 */
export const VOTE_ENTRIES: Record<string, Entry[]> = {}

for (const ev of EVENTS) {
  for (const key of ev.yes) {
    const list = (VOTE_ENTRIES[key] ??= [])
    list.push({
      date: ev.date,
      summary: `${nameOf(key)}在立法院記名表決中投同意票:${ev.what}(同意:反對:棄權 ${ev.tally})。`,
      category: '爭議',
      domains: ['法律制度'],
      context: '議會或立法院提案',
      source: OFFICIAL,
      others: ev.others,
      dispute: { claim: ev.claim, response: ev.response, facts: ev.facts, original: null },
      verified: V,
    })
  }
  for (const key of ev.no ?? []) {
    const list = (VOTE_ENTRIES[key] ??= [])
    list.push({
      date: ev.date,
      summary: `${nameOf(key)}在立法院記名表決中投反對票,反對爭議法案通過:${ev.what}(同意:反對:棄權 ${ev.tally})。`,
      category: '政績',
      domains: ['法律制度'],
      context: '議會或立法院提案',
      source: OFFICIAL,
      others: ev.others,
      dispute: { claim: ev.claim, response: ev.response, facts: ev.facts, original: null },
      verified: V,
    })
  }
}
